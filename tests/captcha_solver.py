def solve(art: list[str]) -> str:
    width = max(len(r) for r in art)

    def ink(y: int, x: int) -> bool:
        return 0 <= y < len(art) and x < len(art[y]) and art[y][x] in "█▓"

    used = [any(ink(y, x) for y in range(len(art))) for x in range(width)]
    answer, x = "", 0
    while x < width:
        if not used[x]:
            x += 1
            continue
        start = x
        while x < width and used[x]:
            x += 1
        top = next(y for y in range(len(art)) if any(ink(y, start + c) for c in range(5)))
        glyph = ["".join("#" if ink(top + r, start + c) else " " for c in range(5)) for r in range(7)]
        answer += next((ch for ch, g in FONT.items() if g == glyph), "?")
    return answer
